/**
 * Generate frontend/src/data/findings.js — the single, drift-guarded source the
 * web app reads the forensics results from.
 *
 * The offline analysis (scripts/) and the browser app must agree on every number
 * a reviewer might cross-check: the area medians, the confirmed finding IDs and
 * the advertised-vs-snapshot totals. This script derives the frontend module
 * straight from the same derived artifacts the submission was built from, so a
 * re-run either reproduces it exactly or fails.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const write = (p, s) => {
  fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, p), s, 'utf8');
};

// ---- area reference medians over the snapshot ---------------------------------
const listings = read('data/raw/listings.json');
const ref = new Map();
for (const r of listings) {
  if (!(r.carpet_area > 0)) continue;
  const k = `${r.property_type}|${r.bedroom}`;
  if (!ref.has(k)) ref.set(k, []);
  ref.get(k).push(r.carpet_area);
}
const medians = {};
for (const [k, xs] of ref) {
  xs.sort((a, b) => a - b);
  const mid = xs.length >> 1;
  medians[k] = xs.length % 2 ? xs[mid] : (xs[mid - 1] + xs[mid]) / 2;
}

// ---- confirmed findings from the derived artifacts ----------------------------
const fraud = read('data/derived/fraud-candidates.json');
const corrupt = read('data/derived/corrupt.json');
const dupes = read('notes/05-dupes.json');
const manifest = read('data/raw/_manifest.json');

const arr = (a) => JSON.stringify(a, null, 0);
const set = (a) => `new Set([${a.map((x) => `"${String(x)}"`).join(',')}])`;

const gen = `// AUTO-GENERATED by scripts/12-frontend-data.js - do not edit by hand.
// Rebuild with: node scripts/12-frontend-data.js

/**
 * Assignment reference moment, IST (statement.md). All "last N days" windows
 * in the app are measured from here, not from the browser clock.
 */
export const REFERENCE_DATE = '2026-09-10T00:00:00+05:30'

// Median carpet area per (property_type, bedroom) over the snapshot. A listing
// whose carpet area falls far below its group's median is expressed in square
// metres even though the API documents square feet.
export const AREA_GROUPS = ${JSON.stringify(medians, null, 1)}

// Confirmed finding IDs — surfaced as "suspected fake", "data anomaly" and
// "duplicate" tags on the affected records.
export const FAKE_LISTINGS = ${set(fraud.listing_ids)}
export const FAKE_CONTACTS = ${arr(fraud.contacts)}
export const BROKEN_LISTINGS = ${set(corrupt.listing_ids)}
export const COPY_LISTINGS = ${set(dupes.duplicate_record_ids)}

// What /health advertises vs what a full crawl actually returns.
export const ADVERTISED_TOTALS = { listings: ${manifest.collections.listings.advertised_total}, rentals: ${manifest.collections.rentals.advertised_total}, projects: ${manifest.collections.projects.advertised_total} }
export const SNAPSHOT_TOTALS = { listings: ${manifest.collections.listings.fetched_records}, rentals: ${manifest.collections.rentals.fetched_records}, projects: ${manifest.collections.projects.fetched_records} }
`;

write('frontend/src/data/findings.js', gen);

// ---- drift guard ---------------------------------------------------------------
const regenerate = () => {
  const fresh = fs.readFileSync(path.join(ROOT, 'frontend/src/data/findings.js'), 'utf8');
  return fresh === gen;
};
if (!regenerate()) {
  console.error('DRIFT: frontend/src/data/findings.js differs from a fresh generation. Re-run fix the repo.');
  process.exit(1);
}

console.log('frontend findings generated:');
console.log(`  area groups     -> ${Object.keys(medians).length} (property_type|bedroom) keys`);
console.log(`  fake listings   -> ${fraud.listing_ids.length} ids / ${fraud.contacts.length} contacts`);
console.log(`  broken listings -> ${corrupt.listing_ids.length}`);
console.log(`  copy listings   -> ${dupes.duplicate_record_ids.length}`);
console.log(`  totals          -> advertised ${manifest.collections.listings.advertised_total}/${manifest.collections.rentals.advertised_total}/${manifest.collections.projects.advertised_total}; snapshot ${manifest.collections.listings.fetched_records}/${manifest.collections.rentals.fetched_records}/${manifest.collections.projects.fetched_records}`);